// Bundle first, then preserve the notices of dependencies that contributed code.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { build } from "esbuild"

const root = fileURLToPath(new URL("../", import.meta.url)).replace(/\/$/, "")
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/extension.ts"],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  external: ["vscode"],
  sourcemap: true,
  outfile: "dist/extension.js",
  metafile: true
})

const dependencies = new Map()
for (const output of Object.values(result.metafile.outputs)) {
  for (const [input, contribution] of Object.entries(output.inputs)) {
    if (contribution.bytesInOutput === 0 || !input.split("/").includes("node_modules")) continue
    // Walk past package.json files that only set a subdirectory's module type.
    let dir = dirname(resolve(root, input))
    while (dir !== root && dir !== dirname(dir)) {
      const manifest = join(dir, "package.json")
      if (existsSync(manifest)) {
        const pkg = JSON.parse(readFileSync(manifest, "utf8"))
        if (pkg.name && pkg.version) {
          dependencies.set(dir, pkg)
          break
        }
      }
      dir = dirname(dir)
    }
    if (!dependencies.has(dir)) throw new Error("No package metadata for bundled input " + input)
  }
}

const sections = [
  "Generated by scripts/build.mjs from esbuild bundle inputs and scripts/grammar-notices.txt.",
  readFileSync(join(root, "scripts/grammar-notices.txt"), "utf8").trim()
]
for (const [dir, pkg] of [...dependencies].sort(([, a], [, b]) => (a.name + "@" + a.version).localeCompare(b.name + "@" + b.version))) {
  const files = readdirSync(dir, { withFileTypes: true })
    .filter((file) => file.isFile() && /^(licen[cs]e|notice|copying)(?:[._-]|$)/i.test(file.name))
    .map((file) => file.name).sort()
  if (!files.some((file) => /^(licen[cs]e|copying)(?:[._-]|$)/i.test(file))) {
    throw new Error("No license file for bundled dependency " + pkg.name + "@" + pkg.version)
  }
  const texts = files.map((file) => {
    const text = readFileSync(join(dir, file), "utf8").trim()
    if (!text) throw new Error("Empty " + file + " for bundled dependency " + pkg.name)
    return file + "\n\n" + text
  })
  sections.push(pkg.name + "@" + pkg.version + " (" + pkg.license + ")\n\n" + texts.join("\n\n"))
}
writeFileSync(join(root, "ThirdPartyNotices.txt"), sections.join("\n\n---------------------------------------------------------\n\n") + "\n")

const license = readFileSync(join(root, "../../LICENSE"), "utf8")
const mitStart = license.search(/^MIT License\r?$/m)
if (mitStart < 0) throw new Error("LICENSE: missing standalone MIT License heading")
writeFileSync(join(root, "LICENSE"), license.slice(mitStart))
