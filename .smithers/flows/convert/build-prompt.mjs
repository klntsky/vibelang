// Writes prompt.md, the convert flow's system prompt: rules, the cheat sheet from
// .smithers/instructions/app.md, and every golden case as an example. Generated, never hand-edited.
//   node .smithers/flows/convert/build-prompt.mjs           write prompt.md
//   node .smithers/flows/convert/build-prompt.mjs --check   exit 1 if prompt.md is stale
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

const here = fileURLToPath(new URL(".", import.meta.url))
const root = join(here, "../../..")

export function cheatSheet(app = readFileSync(join(root, ".smithers/instructions/app.md"), "utf8")) {
  const start = app.indexOf("## Syntax cheat sheet")
  const end = app.indexOf("\n## ", start + 1)
  if (start < 0 || end < 0) throw new Error("app.md has no \"## Syntax cheat sheet\" section")
  return app.slice(start, end).trim()
}

export function goldenCases(dir = join(here, "golden")) {
  return readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort().map((name) => ({
    name,
    input: readFileSync(join(dir, name, "input.ts"), "utf8").trimEnd(),
    expected: readFileSync(join(dir, name, "expected.effeck"), "utf8").trimEnd()
  }))
}

export function buildPrompt() {
  const examples = goldenCases().map((c) => `### ${c.name}\n\nInput:\n\n\`\`\`ts\n${c.input}\n\`\`\`\n\nOutput:\n\n\`\`\`ts\n${c.expected}\n\`\`\``)
  return `<!-- Generated by build-prompt.mjs from instructions/app.md and golden/. Do not edit. -->
# Convert Effect TypeScript to Effeck

You convert one Effect 4 TypeScript file into the equivalent Effeck file.

Answer with exactly one fenced \`ts\` code block holding the whole Effeck file, and nothing else.

- Keep every export, with its name.
- Drop imports from \`"effect"\`: Effeck has Effect's root modules and common functions in scope.
- Use the Effeck forms below wherever the input uses the Effect form they replace.
- Keep the program's behavior. Add nothing the input does not do, and do not explain.

${cheatSheet().replace(/^## /m, "## ")}

## Examples

${examples.join("\n\n")}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = join(here, "prompt.md")
  const next = buildPrompt()
  if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(target, "utf8") } catch { return "" } })()
    if (current !== next) { console.error("prompt.md is stale: run node .smithers/flows/convert/build-prompt.mjs"); process.exit(1) }
    console.log("prompt.md is up to date")
  } else {
    writeFileSync(target, next)
    console.log(`wrote prompt.md (${Buffer.byteLength(next)} bytes, ${goldenCases().length} examples)`)
  }
}
