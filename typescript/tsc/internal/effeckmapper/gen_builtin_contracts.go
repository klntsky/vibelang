//go:build ignore

// Generate the projector's built-in contracts from the reference checker,
// so adding a shipped contract cannot create a second independent list.
package main

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
)

func main() {
	fs := token.NewFileSet()
	f, err := parser.ParseFile(fs, "../effeck/trust.go", nil, 0)
	if err != nil {
		panic(err)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage effeckmapper\n\nvar builtinContracts = ")
	found := false
	ast.Inspect(f, func(n ast.Node) bool {
		v, ok := n.(*ast.ValueSpec)
		if ok && len(v.Names) == 1 && v.Names[0].Name == "builtinContracts" {
			if err := printer.Fprint(&out, fs, v.Values[0]); err != nil {
				panic(err)
			}
			found = true
		}
		return true
	})
	if !found {
		panic("missing builtinContracts")
	}
	out.WriteByte('\n')
	data, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("builtin_contracts_generated.go", data, 0644); err != nil {
		panic(err)
	}
}
